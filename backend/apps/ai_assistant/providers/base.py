import json
import re
import urllib.request
from abc import ABC, abstractmethod
from typing import Any


def post_json(url: str, payload: dict[str, Any], headers: dict[str, str], timeout: int = 12) -> dict[str, Any]:
    """Execute a JSON HTTP POST request and return the decoded response body."""
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers=headers,
    )
    with urllib.request.urlopen(req, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def redact_secret(exc: Exception, secret: str) -> str:
    """Strip sensitive API keys and auth tokens from exception strings before logging."""
    err_msg = str(exc)
    if secret and secret in err_msg:
        err_msg = err_msg.replace(secret, "[REDACTED]")
    err_msg = re.sub(r"(Bearer\s+)[A-Za-z0-9._\-]+", r"\1[REDACTED]", err_msg, flags=re.IGNORECASE)
    err_msg = re.sub(r"([?&]key=)[^&\s]+", r"\1[REDACTED]", err_msg, flags=re.IGNORECASE)
    return err_msg


def infer_triage_metadata(query: str, response_text: str = "") -> tuple[str, bool]:
    """Infer suggested specialization and emergency alert flag safely from query/response text."""
    q = (query or "").lower()
    r = (response_text or "").lower()

    if any(kw in q for kw in ("chest", "heart", "palpitation")):
        spec = "CARDIOLOGY"
    elif any(kw in q for kw in ("skin", "rash", "acne", "eczema", "itching")):
        spec = "DERMATOLOGY"
    elif any(kw in q for kw in ("child", "infant", "baby", "pediatric")):
        spec = "PEDIATRICS"
    elif any(kw in q for kw in ("joint", "bone", "fracture", "knee", "back pain")):
        spec = "ORTHOPEDICS"
    elif any(kw in q for kw in ("migraine", "seizure", "numbness", "dizziness")):
        spec = "NEUROLOGY"
    elif any(kw in q for kw in ("anxiety", "depression", "insomnia", "panic")):
        spec = "PSYCHIATRY"
    else:
        spec = "GENERAL_MEDICINE"

    is_emergency = any(
        kw in q or kw in r
        for kw in (
            "chest pain",
            "difficulty breathing",
            "shortness of breath",
            "stroke",
            "unconscious",
            "call ambulance",
            "emergency care immediately",
            "hospital immediately",
            "call 911",
            "call 108",
        )
    )
    return spec, is_emergency

